def at(n, w, k):
    hits = [x for x in words(n) if norm(x['w']) == w]
    if len(hits) <= k: sys.exit(f"word {w} not in line {n}")
    return hits[k]['s']
cues = []
for n in sorted(FA):
    parts = FA[n]
    starts = [seg[n]['start'] if sp is None else at(n, *sp) for sp, _ in parts]
    for i, (sp, txt) in enumerate(parts):
        a = starts[i] - 0.08
        b = starts[i + 1] - 0.05 if i + 1 < len(parts) else seg[n]['end'] + 0.35
        cues.append([a, b, txt])
for i in range(len(cues) - 1):  # never overlap the next cue
    cues[i][1] = min(cues[i][1], cues[i + 1][0] - 0.04)
